import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
);
const lockPath = path.join(projectRoot, "package-lock.json");
const outputPath = path.join(projectRoot, "THIRD_PARTY_NOTICES.md");
const checkOnly = process.argv.includes("--check");
const licenseOverrides = new Map([
	["exif-parser@0.1.12", "MIT"],
	["format@0.2.2", "MIT"],
	["xmlhttprequest-ssl@2.1.2", "MIT"],
]);
const nameOverrides = new Map([
	["string-width-cjs", "string-width"],
	["strip-ansi-cjs", "strip-ansi"],
	["wrap-ansi-cjs", "wrap-ansi"],
]);

function readJson(filePath) {
	return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function packageName(packagePath) {
	const parts = packagePath.split("node_modules/").at(-1).split("/");
	return parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0];
}

function licenseValue(value) {
	if (typeof value === "string") return value;
	if (Array.isArray(value)) {
		return value
			.map((item) => (typeof item === "string" ? item : item?.type))
			.filter(Boolean)
			.join(" OR ");
	}
	return value?.type;
}

function escapeCell(value) {
	return String(value ?? "—")
		.replaceAll("|", "\\|")
		.replaceAll("\n", " ");
}

function comparePackages(left, right) {
	const leftKey = `${left.name}\0${left.version}`;
	const rightKey = `${right.name}\0${right.version}`;
	return leftKey < rightKey ? -1 : leftKey > rightKey ? 1 : 0;
}

function renderSection(title, packages) {
	const rows = packages
		.sort(comparePackages)
		.map(
			(item) =>
				`| ${escapeCell(item.name)} | ${escapeCell(item.version)} | ${escapeCell(item.license)} |`,
		);

	return [
		`## ${title} (${packages.length})`,
		"",
		"| Package | Version | License |",
		"| --- | --- | --- |",
		...rows,
		"",
	].join("\n");
}

const lock = readJson(lockPath);
if (lock.lockfileVersion !== 3 || !lock.packages) {
	throw new Error("Expected an npm package-lock.json with lockfileVersion 3");
}

const inventory = new Map();
for (const [packagePath, locked] of Object.entries(lock.packages)) {
	if (!packagePath.includes("node_modules/") || !locked.version) continue;

	const pathName = packageName(packagePath);
	const name = nameOverrides.get(pathName) ?? pathName;
	const key = `${name}\0${locked.version}`;
	const overrideKey = `${name}@${locked.version}`;
	const item = {
		name,
		version: locked.version,
		license: licenseValue(locked.license) ?? licenseOverrides.get(overrideKey),
		development: locked.dev === true,
	};
	if (!item.license) {
		throw new Error(
			`No license metadata for ${overrideKey}; verify it and add an explicit override`,
		);
	}
	const existing = inventory.get(key);
	if (!existing || (existing.development && !item.development))
		inventory.set(key, item);
}

const packages = [...inventory.values()];
const runtime = packages.filter((item) => !item.development);
const development = packages.filter((item) => item.development);
const command = "npm run generate-licenses";
const output = [
	"# Third-Party Dependency Notices",
	"",
	`> **AUTOGENERATED FILE — DO NOT EDIT.** Regenerate with \`${command}\`.`,
	"",
	"This deterministic inventory is generated from `package-lock.json`. Dependency classification follows npm's lockfile `dev` flag; a package used in both groups is listed as runtime. Explicit license overrides in the generator cover packages whose lockfile metadata omits a license.",
	"",
	renderSection("Production / runtime dependencies", runtime),
	renderSection("Development / build dependencies", development),
].join("\n");

const rendered = `${output.trimEnd()}\n`;
if (checkOnly) {
	const existing = fs.existsSync(outputPath)
		? fs.readFileSync(outputPath, "utf8")
		: "";
	if (existing !== rendered) {
		throw new Error(
			`${path.relative(projectRoot, outputPath)} is stale; run npm run generate-licenses`,
		);
	}
	console.log(`${path.relative(projectRoot, outputPath)} is up to date.`);
} else {
	fs.writeFileSync(outputPath, rendered, "utf8");
	console.log(
		`Generated ${path.relative(projectRoot, outputPath)} (${packages.length} packages).`,
	);
}
